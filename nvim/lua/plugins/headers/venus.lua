local function group_name(key)
	return ("VenusColor%03d"):format(key:byte())
end

local function compile(source_rows, source_palette)
	local values = {}
	local highlights = {}

	for row_number, row in ipairs(source_rows) do
		if #row.text ~= #row.colors then
			error(("Venus row %d has %d glyphs but %d colors"):format(row_number, #row.text, #row.colors))
		end

		values[row_number] = row.text
		local spans = {}
		local run_key
		local run_start

		for column = 1, #row.colors do
			local key = row.colors:sub(column, column)
			if source_palette[key] == nil then
				error(("Venus row %d column %d uses unknown palette key %q"):format(row_number, column, key))
			end

			if key ~= run_key then
				if run_key ~= nil then
					spans[#spans + 1] = { group_name(run_key), run_start - 1, column - 1 }
				end
				run_key = key
				run_start = column
			end
		end

		if run_key ~= nil then
			spans[#spans + 1] = { group_name(run_key), run_start - 1, #row.colors }
		end
		highlights[row_number] = spans
	end

	return {
		type = "text",
		val = values,
		opts = {
			position = "center",
			hl = highlights,
		},
	}
end

local function render()
	local element = compile(rows, palette)
	for key, color in pairs(palette) do
		vim.api.nvim_set_hl(0, group_name(key), { fg = color })
	end
	return element
end

return {
	compile = compile,
	render = render,
}
